# ---------------------------------------------------------------------------
# Test 3b: staggered discrete operators at the initial state (t = 0)
#
# Pins the staggered-grid machinery pointwise at the initial state: the
# mask-aware edge averaging (water_thickness_staggered), the Mahaffy-like Pi
# (compute_conductivity), the conductivity K = k Wstag^(alpha-1) (Pi + eps^2)
# ^((beta-2)/2), the edge velocity V = -K grad R with the Wstag > 0 guard
# (compute_velocity), and the first-order-upwind flux Q = V W_upwind
# (advective_fluxes), all as pure functions of the dumped initial field W_in
# and the fixed geometry. The expected values are computed here from the C++
# formulas of Routing.cc applied to the dumped W_in/H columns (the dump's
# staggered.csv samples the LAST internal substep, which the continuous
# trajectory does not reproduce pointwise; the initial state is the honest
# pointwise pinning target). rel 1e-12 (the esm evaluates the same formulas
# in f64; cross-language pow() ulps are ~1e-16).
# ---------------------------------------------------------------------------
def staggered_expected():
    """Compute the initial-state staggered fields from the C++ formulas."""
    k = 0.001
    alpha = 1.25
    beta = 1.5
    eps = 1.0 if beta < 2.0 else 0.0
    rho_i, rho_w, g = 910.0, 1000.0, 9.81
    dx = 58064.51612903226

    def W(a, b):
        return f(cell(a, b)['W_in'])

    def Hv(a, b):
        return f(cell(a, b)['H'])

    def grounded(a, b):
        return 1.0 if Hv(a, b) > 0.01 else 0.0

    def R(a, b):
        return rho_i * g * Hv(a, b) + rho_w * g * 0.0  # bed = 0

    def Pi_east(a, b):
        dRdx = (R(a + 1, b) - R(a, b)) / dx
        dRdy = (R(a + 1, b + 1) + R(a, b + 1) - R(a + 1, b - 1) - R(a, b - 1)) / (4.0 * dx)
        return dRdx * dRdx + dRdy * dRdy

    def Pi_north(a, b):
        dRdx = (R(a + 1, b + 1) + R(a + 1, b) - R(a - 1, b + 1) - R(a - 1, b)) / (4.0 * dx)
        dRdy = (R(a, b + 1) - R(a, b)) / dx
        return dRdx * dRdx + dRdy * dRdy

    def Wstag(a, b, o):
        if o == 0:  # east
            gc, ge = grounded(a, b), grounded(a + 1, b)
            if gc:
                return 0.5 * (W(a, b) + W(a + 1, b)) if ge else W(a, b)
            return W(a + 1, b) if ge else 0.0
        else:  # north
            gc, gn = grounded(a, b), grounded(a, b + 1)
            if gc:
                return 0.5 * (W(a, b) + W(a, b + 1)) if gn else W(a, b)
            return W(a, b + 1) if gn else 0.0

    def K(a, b, o):
        ws = Wstag(a, b, o)
        Pi = Pi_east(a, b) if o == 0 else Pi_north(a, b)
        return k * ws ** (alpha - 1.0) * (Pi + eps * eps) ** ((beta - 2.0) / 2.0)

    def V(a, b, o):
        ws = Wstag(a, b, o)
        if ws > 0.0:
            dR = (R(a + 1, b) - R(a, b)) if o == 0 else (R(a, b + 1) - R(a, b))
            return -K(a, b, o) * dR / dx
        return 0.0

    def Q(a, b, o):
        v = V(a, b, o)
        upwind = W(a, b) if v >= 0.0 else (W(a + 1, b) if o == 0 else W(a, b + 1))
        return v * upwind

    return dict(W=W, H=Hv, grounded=grounded, R=R, Wstag=Wstag, K=K, V=V, Q=Q)

